"""Programming basics: Python, C++, Java, C#, JavaScript (50 questions each).

First option of a single/code question is the correct one (shuffled later). w: 1 normal, 2 double points,
0 no points (warm-up for speed). out: expected program output when the correct option is worded differently
('EXC' means the program must fail). Every code question is run by check_prog.py.
"""


def Q(text, opts=None, t=20, type='single', code='', lang='', expl='', w=1, out=None, answers=None, word=''):
    return dict(text=text, opts=opts or [], img=None, t=t, type=type, code=code.strip('\n'), lang=lang, expl=expl,
                w=w, out=out, answers=answers or [], word=word)


def TF(text, true, t=15, expl='', w=1):
    return Q(text, [true], t=t, type='truefalse', expl=expl, w=w)


def coder(lang, text):
    def C(code, opts, t=30, expl='', w=1, out=None, q=text):
        return Q(q, opts, t=t, type='code', code=code, lang=lang, expl=expl, w=w, out=out)
    return C


