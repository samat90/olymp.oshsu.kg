def relabel(apps, schema_editor):
    """Sets category, topics and difficulty by problem name. Problems, submissions and ratings are not touched."""
    Problem = apps.get_model('judge', 'Problem')
    ProblemGroup = apps.get_model('judge', 'ProblemGroup')
    ProblemType = apps.get_model('judge', 'ProblemType')

    groups = {}
    for key, full_name, old_keys in GROUPS:
        group = ProblemGroup.objects.filter(name=key).first()
        if group is None:
            group = ProblemGroup.objects.filter(name__in=old_keys).order_by('id').first() or ProblemGroup(name=key)
        group.name, group.full_name = key, full_name
        group.save()
        groups[key] = group

    types = {}
    for key, full_name in TYPES:
        ptype = ProblemType.objects.filter(name=key).first() or ProblemType(name=key)
        ptype.full_name = full_name
        ptype.save()
        types[key] = ptype

    changed = 0
    for problem in Problem.objects.all():
        if problem.name not in PROBLEMS:
            continue
        group, topics, difficulty = PROBLEMS[problem.name]
        problem.group = groups[group]
        problem.difficulty = difficulty
        problem.save(update_fields=['group', 'difficulty'])
        problem.types.set([types[t] for t in topics])
        changed += 1
    print('  problems relabeled: %d, left as they were: %d' % (changed, Problem.objects.count() - changed))

    # Leftover topics such as "uncategorized" or a second "Графы" are dropped only when no problem uses them.
    for ptype in ProblemType.objects.exclude(name__in=[key for key, _ in TYPES]):
        if not Problem.objects.filter(types=ptype).exists():
            ptype.delete()


