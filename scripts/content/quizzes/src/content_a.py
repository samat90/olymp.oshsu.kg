"""Informatics, Math, Physics. First option of a single/code question is the correct one (shuffled later)."""


def Q(text, opts=None, img=None, t=20, type='single', code='', lang='', expl='', answers=None, word=''):
    return dict(text=text, opts=opts or [], img=img, t=t, type=type, code=code, lang=lang, expl=expl,
                answers=answers or [], word=word)


def TF(text, true, img=None, t=15, expl=''):
    return Q(text, [true], img=img, t=t, type='truefalse', expl=expl)


